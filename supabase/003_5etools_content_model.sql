-- ============================================================
-- D&D CHARACTER MANAGER
-- 003 - 5etools content model
--
-- Purpose:
--   Extend the existing catalogue so it can safely import structured
--   5e.tools data without replacing the current character system.
--
-- Important:
--   This migration is additive. It does not delete or recreate the
--   existing catalogue or character data.
-- ============================================================

-- ------------------------------------------------------------
-- 0. Make the existing item value/weight fields compatible with
-- 5e.tools text values (for example `3 lb`, `15 gp`, `Priceless`).
-- This is safe on the current database where these columns have
-- already been changed to text.
-- ------------------------------------------------------------

alter table public.items
  alter column weight type text using weight::text,
  alter column value type text using value::text;


-- ------------------------------------------------------------
-- 1. Shared content-source catalogue
-- ------------------------------------------------------------

create table if not exists public.content_sources (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  name text,
  edition text not null default '2014',
  source_type text not null default 'book',
  is_official boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint content_sources_edition_check
    check (edition in ('2014', '2024', 'custom')),

  unique (code, edition)
);

create index if not exists content_sources_edition_idx
  on public.content_sources (edition);


-- ------------------------------------------------------------
-- 2. Add stable 5e.tools identity + raw source data
--
-- content_key is generated by the importer and is deliberately
-- separate from the UUID primary key. This prevents name-based
-- collisions when the same named spell/item/etc. exists in more
-- than one source or ruleset.
-- ------------------------------------------------------------

alter table public.races
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.classes
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.subclasses
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.backgrounds
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.spells
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists material_component text,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.features
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;

alter table public.items
  add column if not exists edition text not null default '2014',
  add column if not exists content_key text,
  add column if not exists source_code text,
  add column if not exists page integer,
  add column if not exists raw_data jsonb not null default '{}'::jsonb;


-- ------------------------------------------------------------
-- 3. Normalise source naming
--
-- Existing rows use "source". Keep that column for backwards
-- compatibility with the current application, while the importer
-- uses source_code for the canonical 5e.tools source identifier.
-- ------------------------------------------------------------

update public.races
set source_code = source
where source_code is null and source is not null;

update public.classes
set source_code = source
where source_code is null and source is not null;

update public.subclasses
set source_code = source
where source_code is null and source is not null;

update public.backgrounds
set source_code = source
where source_code is null and source is not null;

update public.spells
set source_code = source
where source_code is null and source is not null;

update public.features
set source_code = source
where source_code is null and source is not null;

update public.items
set source_code = source
where source_code is null and source is not null;


-- ------------------------------------------------------------
-- 4. Edition checks
-- ------------------------------------------------------------

alter table public.races
  drop constraint if exists races_edition_check;

alter table public.races
  add constraint races_edition_check
  check (edition in ('2014', '2024', 'custom'));

alter table public.classes
  drop constraint if exists classes_edition_check;

alter table public.classes
  add constraint classes_edition_check
  check (edition in ('2014', '2024', 'custom'));

alter table public.subclasses
  drop constraint if exists subclasses_edition_check;

alter table public.subclasses
  add constraint subclasses_edition_check
  check (edition in ('2014', '2024', 'custom'));

alter table public.backgrounds
  drop constraint if exists backgrounds_edition_check;

alter table public.backgrounds
  add constraint backgrounds_edition_check
  check (edition in ('2014', '2024', 'custom'));

alter table public.spells
  drop constraint if exists spells_edition_check;

alter table public.spells
